//! Deterministic, on-demand creation of adjacent frontier locations.
//!
//! Frontier candidates are derived from a source location's persisted identity
//! and region coordinate. They do not alter the world graph until the player
//! uses a pending local-map passage. Materialization creates only the requested
//! destination location and (when necessary) its containing region.

use serde::{Deserialize, Serialize};

use super::{locations, routes, MacroCoordinate, RegionCoordinate};
use crate::model::{
    Location, LocationGeographyRecord, Region, RouteDirection, World, WorldRoute,
};

const FRONTIER_ANCHOR_CANDIDATES: usize = 16;
const FRONTIER_ELIGIBILITY_CANDIDATES: usize = 4;

/// Cardinal direction from an existing region into the frontier destination.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FrontierDirection {
    North,
    East,
    South,
    West,
}

impl FrontierDirection {
    pub const ALL: [Self; 4] = [Self::North, Self::East, Self::South, Self::West];

    pub const fn offset(self) -> (i64, i64) {
        match self {
            Self::North => (0, -1),
            Self::East => (1, 0),
            Self::South => (0, 1),
            Self::West => (-1, 0),
        }
    }

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::North => "north",
            Self::East => "east",
            Self::South => "south",
            Self::West => "west",
        }
    }

    pub const fn label(self) -> &'static str {
        match self {
            Self::North => "northern",
            Self::East => "eastern",
            Self::South => "southern",
            Self::West => "western",
        }
    }

    pub fn adjacent_region(self, source: RegionCoordinate) -> Option<RegionCoordinate> {
        let (dx, dy) = self.offset();
        Some(RegionCoordinate {
            x: source.x.checked_add(dx)?,
            y: source.y.checked_add(dy)?,
            stratum: source.stratum,
        })
    }
}

/// Stable information carried by a pending local-map frontier passage.
/// The ID depends on the source's persisted stable geography key, not its
/// runtime entity ID, display name, or map position.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FrontierTarget {
    pub id: String,
    pub target_region: RegionCoordinate,
    pub direction: FrontierDirection,
}

impl FrontierTarget {
    pub fn route_id(&self) -> String {
        format!("route.{}", self.id)
    }

    pub fn location_key(&self) -> String {
        format!("location.{}", self.id)
    }
}

/// Result of materializing one pending frontier passage.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FrontierMaterialization {
    pub region_id: u64,
    pub location_id: u64,
    pub route_id: String,
    pub created_region: bool,
    pub created_location: bool,
}

/// Why a frontier could not be materialized.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FrontierMaterializationError {
    MissingGeography,
    MissingSource,
    InvalidFrontier,
    NoLandApproach,
    RouteIdentityConflict,
}

/// Return frontier candidates for a location, excluding directions that already
/// have a permitted direct route into the adjacent region. No region or location
/// is generated by this query.
pub fn frontier_targets_for_location(world: &World, source_location_id: u64) -> Vec<FrontierTarget> {
    let Some(source_region) = world
        .location_by_id(source_location_id)
        .and_then(|location| world.regions.iter().find(|region| region.id == location.region_id))
        .and_then(|region| region.coordinate)
    else {
        return Vec::new();
    };
    if source_region.stratum != 0 || world.geography_seed.is_none() {
        return Vec::new();
    }

    FrontierDirection::ALL
        .into_iter()
        .filter_map(|direction| frontier_target_for_direction(world, source_location_id, direction))
        .filter(|frontier| {
            !world.routes_from(source_location_id).any(|(_, destination_id)| {
                world
                    .location_by_id(destination_id)
                    .and_then(|location| {
                        world.regions.iter().find(|region| region.id == location.region_id)
                    })
                    .and_then(|region| region.coordinate)
                    == Some(frontier.target_region)
            })
        })
        .filter(|frontier| frontier_has_land_approach(world, source_location_id, frontier))
        .collect()
}

fn frontier_has_land_approach(
    world: &World,
    source_location_id: u64,
    frontier: &FrontierTarget,
) -> bool {
    let Some(seed) = world.geography_seed else {
        return false;
    };
    let Some(source_anchor) = world
        .location_geography
        .iter()
        .find(|record| record.location_id == source_location_id)
        .map(|record| record.anchor)
    else {
        return false;
    };
    locations::frontier_anchor_candidates(
        seed,
        world.geography_ruleset_version,
        frontier.target_region,
        &frontier.location_key(),
        frontier.direction,
        FRONTIER_ELIGIBILITY_CANDIDATES,
    )
    .into_iter()
    .any(|candidate| {
        routes::plan_route(
            seed,
            world.geography_ruleset_version,
            source_anchor,
            candidate,
        )
        .status == routes::RoutePlanningStatus::Planned
    })
}

fn frontier_target_for_direction(
    world: &World,
    source_location_id: u64,
    direction: FrontierDirection,
) -> Option<FrontierTarget> {
    let source_location = world.location_by_id(source_location_id)?;
    let source_region = world
        .regions
        .iter()
        .find(|region| region.id == source_location.region_id)?
        .coordinate?;
    if source_region.stratum != 0 {
        return None;
    }
    let target_region = direction.adjacent_region(source_region)?;
    let stable_key = world
        .location_geography
        .iter()
        .find(|record| record.location_id == source_location_id)?
        .stable_key
        .as_str();
    let key_hash = stable_key
        .bytes()
        .fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
            (hash ^ u64::from(byte)).wrapping_mul(0x100_0000_01b3)
        });
    let id = format!(
        "frontier.{key_hash:016x}.{}.{}.{}.{}.{}",
        source_region.x,
        source_region.y,
        direction.as_str(),
        target_region.x,
        target_region.y
    );
    Some(FrontierTarget {
        id,
        target_region,
        direction,
    })
}

/// Materialize one selected frontier. The operation is idempotent: the same
/// target returns its already-created destination and route. A failed land
/// search does not allocate IDs or leave a partially created region/location.
pub fn materialize_frontier(
    world: &mut World,
    source_location_id: u64,
    frontier: &FrontierTarget,
) -> Result<FrontierMaterialization, FrontierMaterializationError> {
    let expected = frontier_target_for_direction(world, source_location_id, frontier.direction)
        .ok_or(FrontierMaterializationError::MissingGeography)?;
    if expected != *frontier {
        return Err(FrontierMaterializationError::InvalidFrontier);
    }
    let source_anchor = world
        .location_geography
        .iter()
        .find(|record| record.location_id == source_location_id)
        .map(|record| record.anchor)
        .ok_or(FrontierMaterializationError::MissingSource)?;
    if world.location_by_id(source_location_id).is_none() {
        return Err(FrontierMaterializationError::MissingSource);
    }
    let seed = world
        .geography_seed
        .ok_or(FrontierMaterializationError::MissingGeography)?;
    let ruleset = world.geography_ruleset_version;
    let route_id = frontier.route_id();
    let stable_location_key = frontier.location_key();

    let existing_location_id = world
        .location_geography
        .iter()
        .find(|record| record.stable_key == stable_location_key)
        .map(|record| record.location_id);

    if let Some(route) = world.route_by_id(&route_id) {
        let Some(location_id) = existing_location_id else {
            return Err(FrontierMaterializationError::RouteIdentityConflict);
        };
        if !route.connects(source_location_id, location_id) {
            return Err(FrontierMaterializationError::RouteIdentityConflict);
        }
        let location = world
            .location_by_id(location_id)
            .ok_or(FrontierMaterializationError::RouteIdentityConflict)?;
        let region = world
            .regions
            .iter()
            .find(|region| region.id == location.region_id)
            .ok_or(FrontierMaterializationError::RouteIdentityConflict)?;
        if region.coordinate != Some(frontier.target_region)
            || !route.allows_travel(source_location_id, location_id)
        {
            return Err(FrontierMaterializationError::RouteIdentityConflict);
        }
        let region_id = region.id;
        return Ok(FrontierMaterialization {
            region_id,
            location_id,
            route_id,
            created_region: false,
            created_location: false,
        });
    }
    if world.routes.iter().any(|route| route.id == route_id) {
        return Err(FrontierMaterializationError::RouteIdentityConflict);
    }

    let region_id = world
        .regions
        .iter()
        .find(|region| region.coordinate == Some(frontier.target_region))
        .map(|region| region.id);
    if let Some(location_id) = existing_location_id {
        if location_id == source_location_id {
            return Err(FrontierMaterializationError::RouteIdentityConflict);
        }
        let location = world
            .location_by_id(location_id)
            .ok_or(FrontierMaterializationError::RouteIdentityConflict)?;
        let owning_region = world
            .regions
            .iter()
            .find(|region| region.id == location.region_id)
            .ok_or(FrontierMaterializationError::RouteIdentityConflict)?;
        if owning_region.coordinate != Some(frontier.target_region) {
            return Err(FrontierMaterializationError::RouteIdentityConflict);
        }
    }
    if existing_location_id.is_none() && world.next_id <= source_location_id {
        return Err(FrontierMaterializationError::RouteIdentityConflict);
    }

    let existing_record = existing_location_id.and_then(|id| {
        world
            .location_geography
            .iter()
            .find(|record| record.location_id == id)
    });

    let (anchor, route_geography, created_location) = if let Some(record) = existing_record {
        let location_id = existing_location_id.expect("existing geography record has a location");
        let (start, end) = if source_location_id < location_id {
            (source_anchor, record.anchor)
        } else {
            (record.anchor, source_anchor)
        };
        let geography = routes::plan_route(seed, ruleset, start, end);
        if geography.status != routes::RoutePlanningStatus::Planned {
            return Err(FrontierMaterializationError::NoLandApproach);
        }
        (record.anchor, geography, false)
    } else {
        let stable_anchor_key = stable_location_key.as_str();
        let candidates = locations::frontier_anchor_candidates(
            seed,
            ruleset,
            frontier.target_region,
            stable_anchor_key,
            frontier.direction,
            FRONTIER_ANCHOR_CANDIDATES,
        );
        let selected = candidates.into_iter().find_map(|anchor| {
            let geography = routes::plan_route(seed, ruleset, source_anchor, anchor);
            (geography.status == routes::RoutePlanningStatus::Planned)
                .then_some((anchor, geography))
        });
        let (anchor, geography) =
            selected.ok_or(FrontierMaterializationError::NoLandApproach)?;
        (anchor, geography, true)
    };

    let created_region = region_id.is_none();
    let region_id = region_id.unwrap_or(0);
    let next_id_before = world.next_id;
    let region_id = if created_region {
        let id = world.allocate_id();
        world.regions.push(Region {
            id,
            name: format!("Frontier Region ({}, {})", frontier.target_region.x, frontier.target_region.y),
            description: "A newly connected region at the edge of the known world.".to_string(),
            location_ids: Vec::new(),
            coordinate: Some(frontier.target_region),
        });
        id
    } else {
        region_id
    };

    let location_id = if let Some(id) = existing_location_id {
        id
    } else {
        let id = world.allocate_id();
        world.locations.push(Location {
            id,
            name: format!("{} Frontier Approach", frontier.direction.label()),
            description: "A newly charted approach into the neighboring region.".to_string(),
            region_id,
            dangerous: (crate::geography::coordinate_seed(seed, ruleset, anchor) & 3) != 0,
            corpse_ids: Vec::new(),
            exits: Vec::new(),
            spatial_layout: None,
        });
        world
            .regions
            .iter_mut()
            .find(|region| region.id == region_id)
            .expect("the destination region was just resolved")
            .location_ids
            .push(id);
        world.location_geography.push(LocationGeographyRecord {
            location_id: id,
            stable_key: stable_location_key,
            anchor,
            footprint_radius_samples: locations::validated_footprint_radius(
                seed,
                ruleset,
                anchor,
                locations::DEFAULT_FOOTPRINT_RADIUS_SAMPLES,
            ),
        });
        world.location_geography.sort_by_key(|record| record.location_id);
        id
    };

    let mut route = WorldRoute::new(
        route_id.clone(),
        source_location_id,
        location_id,
        RouteDirection::Bidirectional,
    );
    route.geography = Some(route_geography);
    if !world.add_route(route) {
        world.locations.retain(|location| location.id != location_id || !created_location);
        world.location_geography.retain(|record| record.location_id != location_id || !created_location);
        if created_region {
            world.regions.retain(|region| region.id != region_id);
        }
        world.next_id = next_id_before;
        return Err(FrontierMaterializationError::RouteIdentityConflict);
    }

    Ok(FrontierMaterialization {
        region_id,
        location_id,
        route_id,
        created_region,
        created_location,
    })
}

